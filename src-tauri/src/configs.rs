pub fn write_mysql(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = mysql_home(settings, layout)?;
    let etc = layout.etc("mysql");
    std::fs::create_dir_all(&etc)?;
    let port = settings.ports.mysql_server;
    let bind = bind_addresses(settings.versions.mysql.as_deref().is_some_and(|v| release_line(v) >= (8, 0)));
    let socket = if cfg!(windows) {
        String::new()
    } else {
        format!("socket=\"{}\"\n", slash(&layout.tmp().join("mysqld.sock")))
    };
    // MySQL 8.4 ships native passwords off, but many PHP apps and tools still expect
    // them; 9.0 removed the plugin, so the option would stop newer versions starting.
    let native = if settings.versions.mysql.as_deref().is_some_and(|v| release_line(v).0 == 8) {
        "mysql_native_password=ON\n"
    } else {
        ""
    };
    let conf = format!(
        r#"# Generated by LampRabit. Changes are overwritten on every start.
[mysqld]
basedir="{home}"
datadir="{data}"
port={port}
bind-address={bind}
{socket}character-set-server=utf8mb4
collation-server=utf8mb4_0900_ai_ci
log-error="{logs}/mysql-error.log"
pid-file="{tmp}/mysqld.pid"
max_allowed_packet=64M
innodb_buffer_pool_size=256M
# The X Protocol port (33060) isn't needed for PHP and would clash between versions.
mysqlx=OFF
{native}
[client]
port={port}
{socket}default-character-set=utf8mb4
"#,
        home = slash(&home),
        data = slash(&mysql_data(settings, layout)),
        logs = slash(&layout.logs()),
        tmp = slash(&layout.tmp()),
    );
    std::fs::write(etc.join("my.ini"), conf)?;
    Ok(())
}

/// Linux: MySQL's generic builds link against two system libraries, libaio and libnuma.
/// Ubuntu 24.04+ and Debian 13 renamed libaio's file to libaio.so.1t64, which MySQL
/// doesn't find; a link under the old name goes in `lib/compat` of the MySQL folder.
/// Returns that folder for LD_LIBRARY_PATH, or an error naming the packages to install.
#[cfg(not(target_os = "linux"))]
pub fn mysql_libraries(_home: &Path) -> Result<Option<PathBuf>> {
    Ok(None)
}

#[cfg(target_os = "linux")]
pub fn mysql_libraries(home: &Path) -> Result<Option<PathBuf>> {
    let compat = home.join("lib").join("compat");
    let missing = || -> Vec<String> {
        let out = std::process::Command::new("ldd")
            .arg(home.join("bin").join("mysqld"))
            .env("LD_LIBRARY_PATH", &compat)
            .output();
        let text = out.map(|o| String::from_utf8_lossy(&o.stdout).into_owned()).unwrap_or_default();
        text.lines().filter(|l| l.contains("not found")).filter_map(|l| l.split_whitespace().next()).map(str::to_string).collect()
    };
    let mut gone = missing();
    if gone.iter().any(|l| l == "libaio.so.1") {
        let renamed = ["/usr/lib/x86_64-linux-gnu", "/lib/x86_64-linux-gnu", "/usr/lib/aarch64-linux-gnu", "/lib/aarch64-linux-gnu", "/usr/lib64", "/usr/lib"]
            .iter()
            .map(|d| Path::new(d).join("libaio.so.1t64"))
            .find(|p| p.exists());
        if let Some(target) = renamed {
            std::fs::create_dir_all(&compat)?;
            let link = compat.join("libaio.so.1");
            let _ = std::fs::remove_file(&link);
            std::os::unix::fs::symlink(target, &link)?;
            gone = missing();
        }
    }
    if gone.is_empty() {
        return Ok(compat.exists().then_some(compat));
    }
    Err(Error::msg(format!(
        "MySQL needs system libraries that aren't installed ({}). Install them, then start MySQL again: sudo apt install libaio1t64 libnuma1 (Ubuntu 24.04+, Debian 13), sudo apt install libaio1 libnuma1 (older Ubuntu/Debian), or sudo dnf install libaio numactl-libs (Fedora).",
        gone.join(", ")
    )))
}

/// Creates the system tables on first start of a release line. Root gets an empty
/// password, like MariaDB here (and XAMPP/Laragon).
pub async fn init_mysql_data(settings: &Settings, layout: &Layout) -> Result<()> {
    let data = mysql_data(settings, layout);
    if data.join("mysql.ibd").exists() || data.join("mysql").exists() {
        return Ok(());
    }
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        return Err(Error::msg(format!("{} is not empty but has no MySQL system tables; move it away to re-initialise", data.display())));
    }
    let home = mysql_home(settings, layout)?;
    let libs = mysql_libraries(&home)?;
    let mut cmd = tokio::process::Command::new(home.join("bin").join(exe("mysqld")));
    if let Some(dir) = libs {
        cmd.env("LD_LIBRARY_PATH", dir);
    }
    // mysqld creates the data folder itself and refuses one that already exists.
    cmd.arg(format!("--defaults-file={}", layout.etc("mysql").join("my.ini").display()))
        .arg("--initialize-insecure")
        .current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    if !out.status.success() {
        let _ = std::fs::remove_dir_all(&data);
        let log = std::fs::read_to_string(layout.logs().join("mysql-error.log")).unwrap_or_default();
        let reason = log.lines().rev().find(|l| l.contains("[ERROR]")).unwrap_or_default().to_string();
        return Err(Error::msg(format!(
            "MySQL data directory initialisation failed: {}{}{reason}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}

